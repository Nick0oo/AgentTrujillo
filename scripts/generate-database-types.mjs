import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const TARGET_PATH = resolve(process.cwd(), "agent/lib/supabase/database.types.ts");

export function buildGenerateCommand({ source = process.env.SUPABASE_TYPES_SOURCE } = {}) {
  const connection = source === "linked" ? "--linked" : "--local";
  return ["supabase", "gen", "types", "typescript", connection, "--schema", "public"];
}

export function normalizeGeneratedTypes(source) {
  return String(source ?? "")
    .replace(/^\uFEFF/, "")
    .replace(/^\/\/ This file was generated by Supabase\.?\r?\n/m, "")
    .replace(/\r\n?/g, "\n");
}

export function validateGeneratedTypes(source) {
  const normalized = normalizeGeneratedTypes(source);
  if (!normalized.trim()) throw new Error("generated Supabase types are empty");
  if (!normalized.includes("export type Json =")) throw new Error("generated Supabase types are missing Json");
  if (!normalized.includes("export type Database =")) throw new Error("generated Supabase types are missing Database");
  return normalized;
}

export function redactOutput(value) {
  return String(value ?? "")
    .replace(/(?:postgres(?:ql)?:\/\/)[^\s"']+/gi, "[REDACTED]")
    .replace(/(?:[A-Z0-9_]*(?:PASSWORD|TOKEN|SECRET|KEY|ACCESS_TOKEN|SERVICE_ROLE|ANON_KEY))\s*[=:]\s*[^\s,;]+/gi, "$1=[REDACTED]");
}

function cliInvocation(args) {
  if (process.platform !== "win32") return { command: "npx", prefix: [] };
  return {
    command: process.execPath,
    prefix: [join(dirname(process.execPath), "node_modules", "npm", "bin", "npx-cli.js")],
  };
}

export function runLocalGenerator(args = buildGenerateCommand()) {
  const { command, prefix } = cliInvocation(args);
  const result = spawnSync(command, [...prefix, "--no-install", ...args], {
    cwd: process.cwd(),
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
    stdio: ["ignore", "pipe", "pipe"],
    timeout: 120_000,
    windowsHide: true,
  });
  return {
    status: result.status ?? 1,
    stdout: result.stdout ?? "",
    stderr: redactOutput(result.stderr || result.error?.message),
  };
}

export function writeGeneratedTypesAtomic(source, targetPath = TARGET_PATH) {
  const normalized = validateGeneratedTypes(source);
  mkdirSync(dirname(targetPath), { recursive: true });
  const temporaryPath = join(dirname(targetPath), `.database.types.${process.pid}.${Date.now()}.tmp`);
  try {
    writeFileSync(temporaryPath, normalized, "utf8");
    try {
      renameSync(temporaryPath, targetPath);
    } catch (error) {
      if (error?.code !== "EEXIST" && error?.code !== "EPERM") throw error;
      rmSync(targetPath, { force: true });
      renameSync(temporaryPath, targetPath);
    }
  } finally {
    rmSync(temporaryPath, { force: true });
  }
  return { targetPath, bytes: Buffer.byteLength(normalized), lineCount: normalized.split("\n").length - 1 };
}

export function generateDatabaseTypes({ targetPath = TARGET_PATH, runCommand = runLocalGenerator } = {}) {
  const result = runCommand(buildGenerateCommand());
  if (result.status !== 0) {
    throw new Error(`SUPABASE_TYPES_GENERATION_FAILED: ${redactOutput(result.stderr)}`);
  }
  return writeGeneratedTypesAtomic(result.stdout, targetPath);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    const result = generateDatabaseTypes();
    process.stdout.write(`${JSON.stringify(result)}\n`);
  } catch (error) {
    process.stderr.write(`${redactOutput(error.message)}\n`);
    process.exitCode = 1;
  }
}
